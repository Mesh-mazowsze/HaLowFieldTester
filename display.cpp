void dispText(int16_t x, int16_t y, const char *s, uint16_t fg, uint16_t bg,
              uint8_t scale) {
  if (!s_present || !s) return;
  if (scale < 1) scale = 1;

  for (; *s; s++) {
    uint8_t c = (uint8_t)*s;
    if (c < 32 || c > 126) c = '?';
    const uint8_t *g = FONT5X7[c - 32];

    for (uint8_t col = 0; col < 6; col++) {
      uint8_t bits = (col < 5) ? pgm_read_byte(&g[col]) : 0x00;
      for (uint8_t row = 0; row < 8; row++) {
        uint16_t colour = (bits & (1 << row)) ? fg : bg;
        if (colour == bg && bg == TFT_BLACK && !(bits & (1 << row))) {
          /* still paint, so text overwrites cleanly */
        }
        dispFillRect((int16_t)(x + col * scale), (int16_t)(y + row * scale),
                     scale, scale, colour);
      }
    }
    x += 6 * scale;
    if (x > TFT_W) return;
  }
}
