static void wrCmd(uint8_t c) {
  digitalWrite(TFT_PIN_DC, LOW);
  digitalWrite(TFT_PIN_CS, LOW);
  s_spi->transfer(c);
  digitalWrite(TFT_PIN_CS, HIGH);
}

static void wrData(const uint8_t *d, size_t n) {
  digitalWrite(TFT_PIN_DC, HIGH);
  digitalWrite(TFT_PIN_CS, LOW);
  for (size_t i = 0; i < n; i++) s_spi->transfer(d[i]);
  digitalWrite(TFT_PIN_CS, HIGH);
}

static void wrCmdData(uint8_t c, const uint8_t *d, size_t n) {
  wrCmd(c);
  if (n) wrData(d, n);
}

#define C1(C, A)    do { const uint8_t d[] = { (uint8_t)(A) };               wrCmdData((C), d, 1); } while (0)
#define C2(C, A, B) do { const uint8_t d[] = { (uint8_t)(A), (uint8_t)(B) }; wrCmdData((C), d, 2); } while (0)

