#define NV_SWRESET 0x01
#define NV_RDDID   0x04
#define NV_SLPOUT  0x11
#define NV_INVOFF  0x20
#define NV_DISPON  0x29
#define NV_CASET   0x2A
#define NV_RASET   0x2B
#define NV_RAMWR   0x2C
#define NV_MADCTL  0x36
#define NV_COLMOD  0x3A
#define NV_RDID1   0xDA
#define NV_RDID2   0xDB
#define NV_RDID3   0xDC

#define NV_ID_NV3001B 0x300101

static bool s_present = false;
static SPIClass *s_spi = NULL;

/* ------------------------------------------------------------------ */
/* Bit-banged ID read (runs before SPI is configured)                  */
/* ------------------------------------------------------------------ */

static inline void nvDelay(void) { delayMicroseconds(2); }

static void nvWriteCmdForRead(uint8_t cmd) {
  pinMode(TFT_PIN_SDA, OUTPUT);
  digitalWrite(TFT_PIN_DC, LOW);
  for (uint8_t mask = 0x80; mask; mask >>= 1) {
    digitalWrite(TFT_PIN_SCL, LOW);
    digitalWrite(TFT_PIN_SDA, (cmd & mask) ? HIGH : LOW);
    nvDelay();
    digitalWrite(TFT_PIN_SCL, HIGH);
    nvDelay();
    if (mask == 0x01) {
      /* Turn the line around for the reply on the last clock. */
      digitalWrite(TFT_PIN_DC, HIGH);
      pinMode(TFT_PIN_SDA, INPUT);
      nvDelay();
    }
  }
  digitalWrite(TFT_PIN_SCL, LOW);
  nvDelay();
}

static uint8_t nvReadBit(void) {
  digitalWrite(TFT_PIN_SCL, HIGH);
  nvDelay();
  uint8_t b = digitalRead(TFT_PIN_SDA) ? 1 : 0;
  digitalWrite(TFT_PIN_SCL, LOW);
  nvDelay();
  return b;
}

static uint8_t nvReadByte(void) {
  uint8_t d = 0;
  for (uint8_t i = 0; i < 8; i++) d = (uint8_t)((d << 1) | nvReadBit());
  return d;
}

static void nvReadRegister(uint8_t cmd, uint8_t *out, uint8_t len, bool skipBit) {
  digitalWrite(TFT_PIN_CS, LOW);
  nvWriteCmdForRead(cmd);
  if (skipBit) (void)nvReadBit();
  for (uint8_t i = 0; i < len; i++) out[i] = nvReadByte();
  pinMode(TFT_PIN_SDA, OUTPUT);
  digitalWrite(TFT_PIN_SDA, HIGH);
  digitalWrite(TFT_PIN_CS, HIGH);
  digitalWrite(TFT_PIN_DC, HIGH);
  digitalWrite(TFT_PIN_SCL, LOW);
}

uint32_t dispProbeId(void) {
  /* Power the panel: EN is active low. */
  pinMode(TFT_PIN_EN, OUTPUT); digitalWrite(TFT_PIN_EN, LOW);
  pinMode(TFT_PIN_BL, OUTPUT); digitalWrite(TFT_PIN_BL, HIGH);
  delay(50);

  pinMode(TFT_PIN_CS,  OUTPUT);
  pinMode(TFT_PIN_SCL, OUTPUT);
  pinMode(TFT_PIN_SDA, OUTPUT);
  pinMode(TFT_PIN_DC,  OUTPUT);
  pinMode(TFT_PIN_RST, OUTPUT);
  digitalWrite(TFT_PIN_CS,  HIGH);
  digitalWrite(TFT_PIN_DC,  HIGH);
  digitalWrite(TFT_PIN_SCL, LOW);
  digitalWrite(TFT_PIN_SDA, HIGH);
  digitalWrite(TFT_PIN_RST, HIGH);
  delay(100);
  digitalWrite(TFT_PIN_RST, LOW);  delay(120);
  digitalWrite(TFT_PIN_RST, HIGH); delay(120);

  uint8_t rddid[3] = {0}, rdid[3] = {0};
  nvReadRegister(NV_RDDID, rddid, 3, true);
  nvReadRegister(NV_RDID1, &rdid[0], 1, false);
  nvReadRegister(NV_RDID2, &rdid[1], 1, false);
  nvReadRegister(NV_RDID3, &rdid[2], 1, false);

  uint32_t a = ((uint32_t)rddid[0] << 16) | ((uint32_t)rddid[1] << 8) | rddid[2];
  uint32_t b = ((uint32_t)rdid[0]  << 16) | ((uint32_t)rdid[1]  << 8) | rdid[2];

  LOGI("TFT", "RDDID=0x%06lX RDID=0x%06lX", (unsigned long)a, (unsigned long)b);
  if (a == NV_ID_NV3001B) return a;
  if (b == NV_ID_NV3001B) return b;
  return a ? a : b;
}

