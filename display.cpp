bool dispInit(void) {
  uint32_t id = dispProbeId();
  if (id != NV_ID_NV3001B) {
    LOGW("TFT", "no NV3001B found (id 0x%06lX) - display disabled",
         (unsigned long)id);
    s_present = false;
    return false;
  }

  pinMode(TFT_PIN_CS, OUTPUT);  digitalWrite(TFT_PIN_CS, HIGH);
  pinMode(TFT_PIN_DC, OUTPUT);  digitalWrite(TFT_PIN_DC, HIGH);
  pinMode(TFT_PIN_RST, OUTPUT);
  digitalWrite(TFT_PIN_RST, HIGH); delay(10);
  digitalWrite(TFT_PIN_RST, LOW);  delay(20);
  digitalWrite(TFT_PIN_RST, HIGH); delay(120);

  s_spi = new SPIClass(HSPI);
  s_spi->begin(TFT_PIN_SCL, -1, TFT_PIN_SDA, -1);   /* CS driven by hand */
  s_spi->beginTransaction(SPISettings(4000000, MSBFIRST, SPI_MODE0));

  initPanel();
  s_present = true;
  LOGI("TFT", "NV3001B ready, %dx%d", TFT_W, TFT_H);
  return true;
}

bool dispPresent(void) { return s_present; }

void dispBacklight(bool on) {
  pinMode(TFT_PIN_BL, OUTPUT);
  digitalWrite(TFT_PIN_BL, on ? HIGH : LOW);
}

static void setWindow(int16_t x, int16_t y, int16_t w, int16_t h) {
  uint8_t d[4];
  d[0] = (uint8_t)(x >> 8); d[1] = (uint8_t)x;
  d[2] = (uint8_t)((x + w - 1) >> 8); d[3] = (uint8_t)(x + w - 1);
  wrCmdData(NV_CASET, d, 4);
  d[0] = (uint8_t)(y >> 8); d[1] = (uint8_t)y;
  d[2] = (uint8_t)((y + h - 1) >> 8); d[3] = (uint8_t)(y + h - 1);
  wrCmdData(NV_RASET, d, 4);
  wrCmd(NV_RAMWR);
}

void dispFillRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t colour) {
  if (!s_present) return;
  if (x < 0) { w += x; x = 0; }
  if (y < 0) { h += y; y = 0; }
  if (x + w > TFT_W) w = TFT_W - x;
  if (y + h > TFT_H) h = TFT_H - y;
  if (w <= 0 || h <= 0) return;

  setWindow(x, y, w, h);
  uint8_t hi = (uint8_t)(colour >> 8), lo = (uint8_t)colour;
  digitalWrite(TFT_PIN_DC, HIGH);
  digitalWrite(TFT_PIN_CS, LOW);
  for (int32_t i = 0; i < (int32_t)w * h; i++) {
    s_spi->transfer(hi);
    s_spi->transfer(lo);
  }
  digitalWrite(TFT_PIN_CS, HIGH);
}

void dispFill(uint16_t colour) {
  dispFillRect(0, 0, TFT_W, TFT_H, colour);
}

